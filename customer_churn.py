### Q5: Logistic regression: which factors raise the odds of churn?
#Logistic regression estimates how much each factor changes a customer's odds of churning, holding the others constant.
#I included login activity, spending, service contacts and demographics. Login frequency is entered as a Low-login flag
#(5 logins or fewer) because the earlier analysis showed churn is high only in the LOW band, not in a straight line.

#build the table (one row per customer)
import statsmodels.api as sm
from sklearn.model_selection import StratifiedKFold, cross_val_score
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler

# Summarise transactions and service contacts to one row per customer
spend = trans.groupby("CustomerID")["AmountSpent"].agg(Transactions="count", AvgSpend="mean")
svc = service.groupby("CustomerID").agg(
    ServiceContacts=("InteractionID", "count"),
    UnresolvedShare=("ResolutionStatus", lambda s: (s == "Unresolved").mean()))

model_df = (demo.merge(online[["CustomerID", "LoginFrequency"]], on="CustomerID", how="left")
                .merge(spend, on="CustomerID", how="left")
                .merge(svc, on="CustomerID", how="left"))
model_df[["ServiceContacts", "UnresolvedShare"]] = model_df[["ServiceContacts", "UnresolvedShare"]].fillna(0)  # no contacts = 0

model_df["LowLogin"] = (model_df["LoginFrequency"] <= 5).astype(int)   # the LOW risk band
model_df["Churned"] = (model_df["Churn status"] == "YES").astype(int)

numeric = ["Age", "Transactions", "AvgSpend", "ServiceContacts", "UnresolvedShare", "LowLogin"]
categorical = ["Gender", "MaritalStatus", "IncomeLevel"]
print(model_df.shape, "| churn rate:", round(model_df["Churned"].mean() * 100, 1), "%")

# fit the model and show the odds ratios
X = pd.get_dummies(model_df[numeric + categorical], columns=categorical, drop_first=True).astype(float)
scale_cols = [c for c in numeric if c != "LowLogin"]
X[scale_cols] = (X[scale_cols] - X[scale_cols].mean()) / X[scale_cols].std()   # same scale so effects are comparable

logit = sm.Logit(model_df["Churned"], sm.add_constant(X)).fit(disp=0)
results = pd.DataFrame({"Odds ratio": np.exp(logit.params), "p-value": logit.pvalues}).round(3)
results["Significant (p<0.05)"] = results["p-value"] < 0.05
display(results.drop(index="const"))
print("Pseudo R-squared:", round(logit.prsquared, 3))

#how well does it predict? (5-fold cross-validation)
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
pre = ColumnTransformer([("num", StandardScaler(), [c for c in numeric if c != "LowLogin"] + ["LowLogin"]),
                         ("cat", OneHotEncoder(drop="first"), categorical)])
full_model = Pipeline([("pre", pre), ("lr", LogisticRegression(class_weight="balanced", max_iter=1000))])
low_only = Pipeline([("lr", LogisticRegression(class_weight="balanced"))])

auc_full = cross_val_score(full_model, model_df[numeric + categorical], model_df["Churned"], cv=cv, scoring="roc_auc").mean()
auc_low = cross_val_score(low_only, model_df[["LowLogin"]], model_df["Churned"], cv=cv, scoring="roc_auc").mean()
print(f"ROC-AUC, all factors:      {auc_full:.2f}   (0.50 = no better than guessing)")
print(f"ROC-AUC, Low-login only:   {auc_low:.2f}")

"""**Result:** Low login activity is the only factor with a statistically significant effect
(odds ratio about 2.5, p < 0.001): customers with 5 logins or fewer have about 2.5 times the odds of churning.
Age, gender, marital status, income, spending and service contacts are not significant.
The model's predictive power is weak (cross-validated ROC-AUC about 0.53, close to 0.50 = guessing),
so it should not be used to score individual customers. It supports the earlier finding that login frequency is the
signal to monitor, and that the other variables do not explain churn.

Recommendation: Focus retention efforts on customers in the 'LOW' frequency risk band, as they represent a significant segment with a higher propensity to churn. While this segment is valuable, understanding and mitigating the factors contributing to churn in this group could yield greater impact. Further investigation into specific behaviors or demographics within the 'LOW' risk segment is recommended to tailor targeted interventions.
"""